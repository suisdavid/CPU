package cpu2026
import circt.stage.ChiselStage
import java.nio.file.{Files, Paths}
object Generate {
  def main(args: Array[String]): Unit = {
    require(args.length <= 1, "Usage: scala-cli run CPU-chisel -M cpu2026.Generate -- [rtl-directory]")
    val dir = Paths.get(args.headOption.getOrElse("verilog")).toAbsolutePath
    val generated = dir.resolve("generated")
    Files.createDirectories(generated)
    ChiselStage.emitSystemVerilogFile(new StudentTop,
      args = Array("--target-dir", generated.toString),
      firtoolOpts = Array("--disable-all-randomization", "--strip-debug-info", "--lowering-options=disallowLocalVariables,disallowPackedArrays"))
    Files.writeString(dir.resolve("filelist.f"), "# Generated by cpu2026.Generate\ngenerated/student_top.sv\n")
    println(s"Generated ${generated.resolve("student_top.sv")}")
  }
}
